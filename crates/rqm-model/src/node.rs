//! Tree nodes: collection, folder, request.

use serde::{Deserialize, Serialize};

use crate::request::{Auth, RequestContent, Scripts, Variable};
use crate::{is_default, to_json_string, Extra, NodeId};

/// Kind of a tree node. Stored next to the content and decides how the content JSON is read.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum NodeKind {
    /// Root of a tree; the only kind without a parent.
    Collection,
    /// Groups folders and requests inside a collection.
    Folder,
    /// An HTTP request; a leaf of the tree.
    Request,
}

/// One node of the collections tree.
#[derive(Debug, Clone, PartialEq)]
pub struct Node {
    /// Generated by [`crate::new_id`] when the node is created or imported.
    pub id: NodeId,
    /// `None` for a collection, the containing collection or folder otherwise.
    pub parent_id: Option<NodeId>,
    /// Always matches the variant of `content`.
    pub kind: NodeKind,
    /// Name shown in the tree (Postman `name` / `info.name`).
    pub name: String,
    /// Position among the siblings, ascending.
    pub sort_order: i64,
    /// Kind-specific data of the node.
    pub content: NodeContent,
}

/// Kind-specific data of a node. Written to the store as the bare inner structure;
/// the kind is not part of the JSON, so reading needs it from [`Node::kind`].
#[derive(Debug, Clone, PartialEq)]
pub enum NodeContent {
    /// Data of a collection node.
    Collection(CollectionContent),
    /// Data of a folder node.
    Folder(FolderContent),
    /// Data of a request node.
    Request(RequestContent),
}

impl NodeContent {
    /// JSON of the inner structure for the store; defaults and empty parts are skipped.
    pub fn to_json(&self) -> String {
        match self {
            NodeContent::Collection(c) => to_json_string(c),
            NodeContent::Folder(c) => to_json_string(c),
            NodeContent::Request(c) => to_json_string(c),
        }
    }

    /// Reads content written by [`NodeContent::to_json`] for a node of the given kind.
    pub fn from_json(kind: NodeKind, json: &str) -> Result<Self, serde_json::Error> {
        Ok(match kind {
            NodeKind::Collection => NodeContent::Collection(serde_json::from_str(json)?),
            NodeKind::Folder => NodeContent::Folder(serde_json::from_str(json)?),
            NodeKind::Request => NodeContent::Request(serde_json::from_str(json)?),
        })
    }
}

/// Data of a collection.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct CollectionContent {
    /// Authorization inherited by the descendants; `None` = nothing set at this level.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub auth: Option<Auth>,
    /// Collection variables (Postman `variable`).
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub variables: Vec<Variable>,
    /// Scripts of the collection (Postman `event`).
    #[serde(default, skip_serializing_if = "is_default")]
    pub scripts: Scripts,
    /// Original Postman collection object without `item` and `name` (rule P1).
    #[serde(default, skip_serializing_if = "Extra::is_empty")]
    pub postman_extra: Extra,
}

/// Data of a folder.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct FolderContent {
    /// `None` = inherit from the parent; `Some(Auth::NoAuth)` = explicitly no authorization.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub auth: Option<Auth>,
    /// Scripts of the folder (Postman `event`).
    #[serde(default, skip_serializing_if = "is_default")]
    pub scripts: Scripts,
    /// Original Postman folder object without `item` and `name` (rule P1).
    #[serde(default, skip_serializing_if = "Extra::is_empty")]
    pub postman_extra: Extra,
}
