//! Environments and the globals set.

use serde::{Deserialize, Serialize};

use crate::request::Variable;
use crate::{to_json_string, Extra};

/// Fixed identifier of the single globals set.
pub const GLOBALS_ID: &str = "globals";

/// Kind of a variable set.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum EnvKind {
    /// An environment chosen by the user for a request.
    Environment,
    /// The globals set: exists once and always applies.
    Globals,
}

/// An environment or the globals set.
#[derive(Debug, Clone, PartialEq)]
pub struct Environment {
    /// [`GLOBALS_ID`] for globals, otherwise generated by [`crate::new_id`].
    pub id: String,
    /// Follows from `id`: `Globals` only for [`GLOBALS_ID`].
    pub kind: EnvKind,
    /// Name shown in the interface (Postman `name`).
    pub name: String,
    /// Variables of the set (Postman `values`).
    pub variables: Vec<Variable>,
    /// Original Postman environment object without `name` (rule P1).
    pub postman_extra: Extra,
}

/// The part of an environment kept in the store's `content` column.
#[derive(Serialize)]
struct ContentRef<'a> {
    #[serde(skip_serializing_if = "<[Variable]>::is_empty")]
    variables: &'a [Variable],
    #[serde(skip_serializing_if = "Extra::is_empty")]
    postman_extra: &'a Extra,
}

/// Owned counterpart of [`ContentRef`] for reading.
#[derive(Deserialize)]
struct Content {
    #[serde(default)]
    variables: Vec<Variable>,
    #[serde(default)]
    postman_extra: Extra,
}

impl Environment {
    /// The globals set before anything is added to it.
    pub fn empty_globals() -> Self {
        Environment {
            id: GLOBALS_ID.to_string(),
            kind: EnvKind::Globals,
            name: "Globals".to_string(),
            variables: Vec::new(),
            postman_extra: Extra::new(),
        }
    }

    /// JSON for the store: `{"variables": [...], "postman_extra": {...}}` (empty parts are skipped).
    pub fn content_json(&self) -> String {
        to_json_string(&ContentRef { variables: &self.variables, postman_extra: &self.postman_extra })
    }

    /// Builds an environment from the store's columns.
    /// `kind` is `Globals` when `id == GLOBALS_ID`, otherwise `Environment`.
    pub fn from_parts(id: &str, name: &str, content_json: &str) -> Result<Self, serde_json::Error> {
        let content: Content = serde_json::from_str(content_json)?;
        Ok(Environment {
            id: id.to_string(),
            kind: if id == GLOBALS_ID { EnvKind::Globals } else { EnvKind::Environment },
            name: name.to_string(),
            variables: content.variables,
            postman_extra: content.postman_extra,
        })
    }
}
